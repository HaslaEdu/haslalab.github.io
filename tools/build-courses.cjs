#!/usr/bin/env node
/* Builds data/courses.json for the courses page (#/learn/courses) from what is already in the repository:
   the four study levels (practice-tools.js STUDY_LEVELS), the practice problems (practice/), the units of the learning
   path (learn-path.js), the concept simulations (concepts.js), the computational physics problems (compute-problems.js)
   and the roadmap stages (data/roadmap.json). Nothing is written by hand: a unit is in a level's course when that level's
   problems include it. `--check` fails when the file is out of date.
   Usage: node tools/build-courses.cjs [--check] */
'use strict';
const fs=require('fs'),path=require('path');
const ROOT=path.join(__dirname,'..'),read=f=>fs.readFileSync(path.join(ROOT,f),'utf8'),json=f=>JSON.parse(read(f));
const P=require('../learn-path.js'),T=require('../practice-tools.js'),C=require('../compute-problems.js');

/* which roadmap stages (data/roadmap.json keys) each level's course points to */
const ROADMAP={L1:['start','school','exam','olympiad1'],L2:['exam'],L3:['olympiad1','olympiad2'],L4:['undergrad','upper']};

function build(){
  const calc=[];
  for(const f of fs.readdirSync(path.join(ROOT,'practice/data')).filter(f=>f.endsWith('.json')).sort())
    for(const i of json('practice/data/'+f).items)calc.push({u:i.u,s:Number(i.s)});
  const tracks=json('practice/tracks.json').tracks,track={};
  for(const t of tracks)track[t.key]=json('practice/track/'+t.key+'.json').items.map(i=>({u:i.unit,s:Number(i.step)}));
  const contests=json('practice/contests.json').contests,contest={};
  for(const c of contests)contest[c.key]=json('practice/contest/'+c.key+'.json').items.length;

  /* concept simulations: id, unit and title from concepts.js */
  const sims=[...read('concepts.js').matchAll(/\{id:'([a-z0-9-]+)',unit:'([a-z_]+\/[a-z_]+)',title:L\('([^']*)','([^']*)'\)/g)].map(m=>({id:m[1],u:m[2],name:{ko:m[3],en:m[4]}}));
  const compute=C.PROBLEMS.map(p=>({id:p.id,u:p.area+'/'+p.subtopic,step:p.step,name:{ko:p.title.ko,en:p.title.en}}));
  const order=[];for(const a of P.AREAS)for(const s of a.subtopics)order.push(a.key+'/'+s.key);

  const levels=T.STUDY_LEVELS.map(L=>{
    const items=[...(L.calc?calc:[]),...L.tracks.flatMap(k=>track[k]||[])];
    const by={};for(const i of items)if(P.SUBTOPICS.has(i.u))(by[i.u]||=[]).push(i.s);
    const units=order.filter(u=>by[u]).map(u=>({u,n:by[u].length,steps:[Math.min(...by[u]),Math.max(...by[u])]}));
    /* the books & university level has no unit-tagged problems in practice/: its course goes area by area to the
       problem bank's subjects (problem search) */
    const areas=L.bank?P.AREAS.filter(a=>a.bank).map(a=>({area:a.key,bank:a.bank})):[];
    return{key:L.key,name:L.name,has:L.has,soon:L.soon,units,areas,tracks:L.tracks.map(k=>({key:k,n:(track[k]||[]).length})),calc:L.calc?calc.length:0,
      contests:L.contests.map(k=>({key:k,n:contest[k]||0})),bank:!!L.bank,roadmap:ROADMAP[L.key]||[]};
  });
  const nTrack=Object.values(track).reduce((n,a)=>n+a.length,0),nContest=Object.values(contest).reduce((n,x)=>n+x,0);
  return{note:'generated by tools/build-courses.cjs; do not edit',
    counts:{calc:calc.length,track:nTrack,contest:nContest,total:calc.length+nTrack+nContest,concepts:sims.length,compute:compute.length},
    levels,sims,compute,
    trackNames:Object.fromEntries(tracks.map(t=>[t.key,t.name])),contestNames:Object.fromEntries(contests.map(c=>[c.key,c.name]))};
}
const out=JSON.stringify(build(),null,1)+'\n',file=path.join(ROOT,'data/courses.json');
if(require.main===module){
  if(process.argv.includes('--check')){
    const now=fs.existsSync(file)?fs.readFileSync(file,'utf8'):'';
    if(now!==out){console.error('data/courses.json is out of date: run node tools/build-courses.cjs');process.exit(1);}
    console.log('data/courses.json is up to date.');
  }else{fs.writeFileSync(file,out);const c=JSON.parse(out).counts;console.log('Wrote data/courses.json:',JSON.stringify(c));}
}
module.exports={build};
