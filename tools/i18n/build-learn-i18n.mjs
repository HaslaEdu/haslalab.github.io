/* Builds learn-i18n.js: the Learn section's strings in the languages beyond Korean and English. The source of truth is
   tools/i18n/learn-en.json (every English string the Learn pages show) and tools/i18n/learn-<lang>.json (English → that
   language). A page looks a string up by its English text; anything missing shows in English.
   usage: node tools/i18n/build-learn-i18n.mjs [--check] */
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
export const LANGS = {es: 'Español', pt: 'Português', id: 'Bahasa Indonesia', vi: 'Tiếng Việt', hi: 'हिन्दी'};
const spans = s => [...String(s).matchAll(/\$\$[\s\S]+?\$\$|\$[^$\n]+?\$|`[^`\n]+`/g)].map(m => m[0]);

export function build() {
  const en = JSON.parse(fs.readFileSync(path.join(root, 'tools/i18n/learn-en.json'), 'utf8')).map(x => x.en);
  const wanted = new Set(en), dict = {}, report = {};
  for (const lang of Object.keys(LANGS)) {
    const file = path.join(root, 'tools/i18n', `learn-${lang}.json`);
    const src = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : {};
    const out = {};
    let dropped = 0;
    for (const s of en) {
      const t = src[s];
      if (typeof t !== 'string' || !t.trim()) continue;
      /* a translation that changed the math or the code would teach something else: English is shown instead */
      const a = spans(s), b = spans(t);
      if (a.length !== b.length || a.some((x, i) => x !== b[i])) { dropped++; continue; }
      out[s] = t;
    }
    dict[lang] = out;
    report[lang] = {have: Object.keys(out).length, of: wanted.size, dropped};
  }
  const js = `/* Generated by tools/i18n/build-learn-i18n.mjs from tools/i18n/learn-*.json: do not edit by hand.
   The Learn section's strings beyond Korean and English, looked up by their English text. */
(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;else root.HL_I18N=api;})(typeof self!=='undefined'?self:this,function(){
  'use strict';
  const NAMES=${JSON.stringify({ko: '한국어', en: 'English', ...LANGS})};
  const DICT=${JSON.stringify(dict)};
  return {LANGS:Object.keys(NAMES),NAMES,t(en,lang){const d=DICT[lang];return d&&typeof en==='string'&&Object.prototype.hasOwnProperty.call(d,en)?d[en]:en;}};
});
`;
  return {js, report};
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const {js, report} = build(), target = path.join(root, 'learn-i18n.js');
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== js) { console.error('learn-i18n.js is stale: run node tools/i18n/build-learn-i18n.mjs'); process.exit(1); }
    console.log('learn-i18n.js up to date', JSON.stringify(report));
  } else { fs.writeFileSync(target, js); console.log(JSON.stringify(report)); }
}
