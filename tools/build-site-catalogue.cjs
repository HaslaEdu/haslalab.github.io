/* Build compact navigation metadata and per-competition data chunks from the authoritative sources.
 * node tools/build-site-catalogue.cjs [--check]
 */
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),check=process.argv.includes('--check');
const derivedSources=new Map();
const read=f=>derivedSources.get(f)??fs.readFileSync(path.join(root,f),'utf8').replace(/\r\n/g,'\n');
const digest=s=>crypto.createHash('sha256').update(s).digest('hex').slice(0,12);
const networkVersion=digest(read('sim/exam-network.js'));
const networkArena=read('arena.js').replace(/import\((['"])\.\/sim\/exam-network\.js(?:\?[^'"\n]*)?\1\)/g,(_match,q)=>'import('+q+'./sim/exam-network.js?v='+networkVersion+q+')');
derivedSources.set('arena.js',networkArena);
const window={},scope={window,URL,URLSearchParams,localStorage:{getItem:()=>null},console};
vm.createContext(scope);
const sourceFiles=['paper-languages.js','theory.js','contest-exams.js','iypt.js','usaco.js','rupho-selection.js','rupho-archive.js'];
for(const f of sourceFiles)vm.runInContext(read(f),scope,{filename:f});
const html=read('index.html'),main=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].find(m=>m[1].includes('const REL ='))[1];
const begin=main.indexOf('const REL ='),end=main.indexOf('let lang = new URLSearchParams');
if(begin<0||end<0)throw Error('Archive bootstrap markers changed');
vm.runInContext(main.slice(begin,end)+'\nglobalThis.catalogueData={DATA,THEORY};',scope,{filename:'catalogue-bootstrap.js'});
const {DATA,THEORY}=scope.catalogueData,outputs=new Map(),versions={};
const generated='/* Generated by tools/build-site-catalogue.cjs; edit the source datasets instead. */\n';
// All scanner entry points must load the same content-versioned engine. Derive
// these before hashing their parents so one build updates the full import chain.
const scannerFiles=['scanner.js','document-detector.mjs','document-worker.mjs','document-model.mjs'].map(file=>'sim/labscan/'+file);
const scannerImport=/(['"])(\.\/(?:scanner\.js|document-(?:detector|worker|model)\.mjs))(?:\?v=[a-f0-9]{12})?\1/g;
// The worker imports pure scanner helpers, so this module graph is cyclic.
// Hash the unversioned group, then stamp every edge with one revision.
const scannerVersion=digest(scannerFiles.map(file=>read(file).replace(scannerImport,(_match,q,name)=>q+name+q)).join('\n'));
for(const file of scannerFiles){
  const source=read(file).replace(scannerImport,(_match,q,name)=>q+name+'?v='+scannerVersion+q);
  derivedSources.set(file,source);outputs.set(file,source);
}
for(const file of ['sim/scan.html','sim/scanbench.html','sim/contest-review.js']){
  const source=read(file).replace(/(['"])\.\/labscan\/scanner\.js(?:\?[^'"\n]*)?\1/g,(_match,quote)=>quote+'./labscan/scanner.js?v='+scannerVersion+quote);
  derivedSources.set(file,source);outputs.set(file,source);
}
const arenaScanner=read('arena.js').replace(/(['"])\.\/sim\/labscan\/scanner\.js(?:\?[^'"\n]*)?\1/g,(_match,q)=>q+'./sim/labscan/scanner.js?v='+scannerVersion+q);
derivedSources.set('arena.js',arenaScanner);outputs.set('arena.js',arenaScanner);
// theoryGroups and its dependencies are part of the archive bootstrap above.
// Extract the real experiment selector without executing page rendering or calling yearPair.
const groupBegin=main.indexOf('const examTask='),groupEnd=main.indexOf('/* a year sat as a set',groupBegin);
if(groupBegin<0||groupEnd<0)throw Error('Exam grouping markers changed');
vm.runInContext(main.slice(groupBegin,groupEnd)+'\nglobalThis.catalogueGroups={theoryGroups,examGroups,thyOf,examTask};',scope,{filename:'catalogue-exam-groups.js'});
const {buildPairCatalogue}=require('./lab-pair-catalogue.cjs');
const sourceManifests=new Map();
const officialTheoryParts=(comp,year)=>{
  if(!sourceManifests.has(comp)){
    const file='tools/theory/'+comp+'.json';
    sourceManifests.set(comp,fs.existsSync(path.join(root,file))?JSON.parse(read(file)):null);
  }
  return sourceManifests.get(comp)?.years?.find(row=>String(row.y)===String(year))?.problems?.map(problem=>problem.id);
};
const pairProfiles=buildPairCatalogue(DATA,{...scope.catalogueGroups,officialTheoryParts});
const mixedProfiles={};
for(const [comp,competition]of Object.entries(DATA))for(const year of competition.years){
  const sets=new Map();
  for(const group of scope.catalogueGroups.examGroups(comp,year)){
    if(!group.some(problem=>problem.thy))continue;
    const tasks=group.map(scope.catalogueGroups.examTask);
    if(!tasks.length||tasks.length>4||new Set(tasks).size!==tasks.length||!tasks.every(task=>/^[A-Z][A-Za-z0-9]{0,3}$/.test(task)))
      throw Error('Unsupported mixed exam task set: '+comp+'/'+year.y);
    const canonical=[...tasks].sort();sets.set(canonical.join('|'),canonical);
  }
  if(sets.size)(mixedProfiles[comp]||(mixedProfiles[comp]={}))[String(year.y)]=[...sets.values()];
}
outputs.set('community/src/lab-pair-catalog.js',generated+'export const LAB_PAIR_CATALOGUE='+JSON.stringify(pairProfiles)+';\n'+
  'export const LAB_MIXED_CATALOGUE='+JSON.stringify(mixedProfiles)+';\n');
const {buildModelTestCatalogue}=require('./model-test-catalogue.cjs');
const modelTestExams=buildModelTestCatalogue(DATA,{...scope.catalogueGroups,contests:window.CONTEST_EXAMS});
const modelTestVersion=digest(JSON.stringify(modelTestExams)+read('pdf-assets.json'));
outputs.set('community/src/model-test-catalog.js',generated+'export const MODEL_TEST_CATALOGUE_VERSION='+JSON.stringify(modelTestVersion)+';\n'+
  'export const MODEL_TEST_EXAMS='+JSON.stringify(modelTestExams)+';\n');
const dataKeys=[...new Set([...Object.keys(THEORY),...Object.keys(window.THEORY_META||{}),...Object.keys(window.GENERAL||{})])];
for(const key of dataKeys){
  const name='catalogue/theory-'+key+'.js';
  const source=generated+'window.THEORY=window.THEORY||{};Object.assign(window.THEORY,'+JSON.stringify(Object.hasOwn(THEORY,key)?{[key]:THEORY[key]}:{})+');\n'+
    'window.THEORY_META=window.THEORY_META||{};Object.assign(window.THEORY_META,'+JSON.stringify(window.THEORY_META?.[key]?{[key]:window.THEORY_META[key]}:{})+');\n'+
    (window.GENERAL?.[key]?'window.GENERAL=window.GENERAL||{};Object.assign(window.GENERAL,'+JSON.stringify({[key]:window.GENERAL[key]})+');\n':'')+
    (key==='kphe'&&window.KPHE_PDF_VERSIONS?'window.KPHE_PDF_VERSIONS=Object.assign(window.KPHE_PDF_VERSIONS||{},'+JSON.stringify(window.KPHE_PDF_VERSIONS)+');\n':'');
  outputs.set(name,source);versions['theory:'+key]=name+'?v='+digest(source);
}
for(const key of ['kmo','kmchc']){
  const c=window.CONTEST_EXAMS,subset={checkedAt:c.checkedAt,competitions:{[key]:c.competitions[key]},entries:c.entries.filter(e=>e.comp===key),resources:c.resources.filter(e=>e.comp===key)};
  const name='catalogue/contest-'+key+'.js';
  const source=generated+'(function(){const add='+JSON.stringify(subset)+';const c=window.CONTEST_EXAMS||(window.CONTEST_EXAMS={competitions:{},entries:[],resources:[]});Object.assign(c.competitions,add.competitions);c.checkedAt=add.checkedAt;c.entries=c.entries.filter(e=>e.comp!=='+JSON.stringify(key)+').concat(add.entries);c.resources=c.resources.filter(e=>e.comp!=='+JSON.stringify(key)+').concat(add.resources);})();\n';
  outputs.set(name,source);versions['contest:'+key]=name+'?v='+digest(source);
}
for(const [key,name]of Object.entries({iypt:'iypt.js',usaco:'usaco.js',rupho:'rupho-selection.js',arena:'arena.js','developer-guide':'developer-server-guide.js'}))versions[key]=name+'?v='+digest(read(name));
const competitions={};let years=0,probs=0,live=0,thy=0;
for(const [key,c]of Object.entries(DATA)){
  const data={};for(const k of ['abbr','since','full','scope','plain','rounds','omr','open','obs','note','soon','chip','resources','officialWebsite','officialWebsiteArchived'])if(c[k]!==undefined)data[k]=c[k];
  const exp=c.years.reduce((n,y)=>n+y.problems.length,0),theory=Object.values(THEORY[key]||{}).reduce((n,t)=>n+(t.p?.length||Object.keys(t.f||{}).filter(k=>!t.f[k].kx).length),0);
  competitions[key]={data,counts:{years:c.years.length,hasProblems:c.years.some(y=>y.problems.length),mixed:!!c.theoryCount,problems:c.theoryCount?c.theoryCount+exp:c.years.some(y=>y.problems.length)?exp:theory}};
  years+=c.years.length;
  for(const y of c.years){if(!c.plain)probs+=y.problems.length;live+=y.problems.filter(p=>!p.hold&&p.files&&(p.files.sim||p.files.exe)).length;}
}
for(const data of Object.values(THEORY))for(const y of Object.values(data))thy+=Object.keys(y.f||{}).filter(k=>!y.f[k].kx).length;
const metadata={competitions,theoryKeys:dataKeys,versions,pairProfiles,mixedProfiles,totals:{comps:Object.keys(DATA).length,years,probs,live,thy}};
const metadataSource=generated+'window.HL_CATALOGUE='+JSON.stringify(metadata)+';\n';outputs.set('site-catalogue.js',metadataSource);
let expectedHtml=html.replace(/<script src="site-catalogue\.js(?:\?[^"\n]*)?"><\/script>/,'<script src="site-catalogue.js?v='+digest(metadataSource)+'"></script>')
  .replace(/<link rel="stylesheet" href="site-design\.css(?:\?[^"\n]*)?">/,'<link rel="stylesheet" href="site-design.css?v='+digest(read('site-design.css'))+'">')
  .replace(/<script src="site-runtime\.js(?:\?[^"\n]*)?"><\/script>/,'<script src="site-runtime.js?v='+digest(read('site-runtime.js'))+'"></script>')
  .replace(/<script src="site-design\.js(?:\?[^"\n]*)?"><\/script>/,'<script src="site-design.js?v='+digest(read('site-design.js'))+'"></script>');
for(const file of ['paper-languages.js','examdur.js','rupho-archive.js','logo/variants.js','sim/result-comparison.js'])expectedHtml=expectedHtml.replace(new RegExp('<script src="'+file.replaceAll('.','\\.')+'(?:\\?[^"\\n]*)?"></script>'),'<script src="'+file+'?v='+digest(read(file))+'"></script>');
expectedHtml=expectedHtml.replace(/<script src="monthly-figures\.js(?:\?[^"\n]*)?"><\/script>/,'<script src="monthly-figures.js?v='+digest(read('monthly-figures.js'))+'"></script>');
outputs.set('index.html',expectedHtml);
let examHtml=read('sim/exam.html');
for(const file of ['result-comparison.js','exam-network.js'])examHtml=examHtml.replace(new RegExp('src="'+file.replaceAll('.','\\.')+'(?:\\?[^"\\n]*)?"'),'src="'+file+'?v='+digest(read('sim/'+file))+'"');
outputs.set('sim/exam.html',examHtml);
let contestHtml=read('sim/contest-exam.html');
for(const file of ['../contest-exams.js','contest-review.js','contest-exam.js','exam-network.js']){
  const source=path.posix.normalize('sim/'+file);
  contestHtml=contestHtml.replace(new RegExp('src="'+file.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+'(?:\\?[^"\\n]*)?"'),'src="'+file+'?v='+digest(read(source))+'"');
}
outputs.set('sim/contest-exam.html',contestHtml);
const sheetModule=read('sim/monthly-answer-sheet.mjs').replace(/from '\.\.\/monthly-problems\.mjs(?:\?[^'\n]*)?'/,"from '../monthly-problems.mjs?v="+digest(read('monthly-problems.mjs'))+"'");
outputs.set('sim/monthly-answer-sheet.mjs',sheetModule);
outputs.set('sim/monthly-answer-sheet.html',read('sim/monthly-answer-sheet.html').replace(/src="monthly-answer-sheet\.mjs(?:\?[^"\n]*)?"/,'src="monthly-answer-sheet.mjs?v='+digest(sheetModule)+'"'));
const monthlyScanVersion=digest(read('sim/monthly-scan.mjs'));
outputs.set('sim/monthly-scan.html',read('sim/monthly-scan.html').replace(/src="monthly-scan\.mjs(?:\?[^"\n]*)?"/,'src="monthly-scan.mjs?v='+monthlyScanVersion+'"'));
outputs.set('sim/scan.html',read('sim/scan.html').replace(/import\("\.\/monthly-scan\.mjs(?:\?[^"\n]*)?"\)/,'import("./monthly-scan.mjs?v='+monthlyScanVersion+'")')
  .replace(/src="exam-network\.js(?:\?[^"\n]*)?"/,'src="exam-network.js?v='+networkVersion+'"'));
const stale=[];
for(const [name,content]of outputs){const file=path.join(root,name);if(check){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')!==content.replace(/\r\n/g,'\n'))stale.push(name);}else{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,content);}}
if(stale.length){console.error('Generated catalogue is stale: '+stale.join(', '));process.exitCode=1;}
else console.log((check?'Checked ':'Built ')+(outputs.size-1)+' catalogue files; metadata '+Buffer.byteLength(metadataSource)+' bytes, '+metadata.totals.comps+' competitions.');
