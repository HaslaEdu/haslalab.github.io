"""Bundle trusted answer keys and only verified scoring weights into the Worker."""
import hashlib
import json
from pathlib import Path
from kphe_review import review_questions
ROOT=Path(__file__).resolve().parents[1]
def main():
    manifest=json.loads((ROOT/'tools/theory/kphe.json').read_text(encoding='utf-8'))
    rules=json.loads((ROOT/'tools/kphe_scoring_policy.json').read_text(encoding='utf-8'))
    reviews=review_questions()
    out={}
    for year in manifest['years']:
        for part,key in year.get('keys',{}).items():
            verified=rules.get('exams',{}).get(str(year['y']),{}).get(part,{})
            policy=verified if verified.get('verified') is True else {
                'verified':False,'sources':['https://kphe.kps.or.kr/notice/notice_detail/386'],
                'reason':'공식 문항 배점·분야별 비중·최종 점수 상세 산식 미확보. 감점 정답수는 별도 연습 지표입니다.'}
            eid=f"kphe:{year['y']}:{part}"
            entry={'id':eid,'key':key,'penaltyRate':rules['conclusion']['penalty_rate'],'policy':policy,
                   'reviewQuestions':reviews.get(str(year['y']),{}).get(part,[]),
                   'fullCredit':[c['number'] for c in year.get('corrections',[]) if c['part']==part and c.get('full_credit')]}
            entry['version']=hashlib.sha256(json.dumps(entry,sort_keys=True,ensure_ascii=False).encode()).hexdigest()[:16]
            out[eid]=entry
    (ROOT/'community/src/omr-catalog.js').write_text('/* Generated by tools/kphe_scoring_build.py. */\nexport const OMR_CATALOG = '+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    schema=(ROOT/'community/migrations/0012_omr.sql').read_text(encoding='utf-8')
    statements=[statement.strip() for statement in schema.split(';') if statement.strip()]
    (ROOT/'community/src/omr-schema.js').write_text('/* Generated from migrations/0012_omr.sql. */\nexport const OMR_SCHEMA = '+json.dumps(statements)+';\n',encoding='utf-8')
    print(f'Bundled {len(out)} trusted OMR exams')
if __name__=='__main__': main()
